export function makeT(lang) {
  return (key) => translations[lang]?.[key] ?? translations.tr[key] ?? key;
}

export const LangContext = createContext({
  lang: "tr",
  t: makeT("tr"),
  toggleLang: () => {},
});

export function useLang() {
  return useContext(LangContext);
}